public class Main {
    public static void main(String[] args)
    {

        // initializing array by values
        int[] arr = { 13, 82, 90, 20, 21 };

        // size of array
        int n = arr.length;

        // traversing array
        for (int i = 0; i < n; i++)
            System.out.print(arr[i] + " ");
    }
}
